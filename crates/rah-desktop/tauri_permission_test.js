"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = __dirname;
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), "utf8");
const allowId = (name) => `allow-${name.replaceAll("_", "-")}`;

function unique(names, label) {
  const duplicates = names.filter((name, index) => names.indexOf(name) !== index);
  assert.deepEqual([...new Set(duplicates)].sort(), [], `${label} has duplicate entries`);
  return new Set(names);
}

function equalSets(actual, expected, label) {
  const missing = [...expected].filter((name) => !actual.has(name)).sort();
  const surplus = [...actual].filter((name) => !expected.has(name)).sort();
  assert.deepEqual({ missing, surplus }, { missing: [], surplus: [] }, label);
}

function oneBody(source, expression, label) {
  const matches = [...source.matchAll(expression)];
  assert.equal(matches.length, 1, `${label} must occur exactly once`);
  return matches[0][1];
}

const handlerBody = oneBody(
  read("src/main.rs"),
  /\.invoke_handler\(tauri::generate_handler!\[([\s\S]*?)\]\)/g,
  "runtime generate_handler",
);
const handlerItems = handlerBody.split(",").map((item) => item.trim()).filter(Boolean);
assert.ok(handlerItems.length > 0, "runtime handler inventory is empty");
for (const item of handlerItems) {
  assert.match(item, /^(?:[A-Za-z_][A-Za-z_0-9]*::)*[A-Za-z_][A-Za-z_0-9]*$/, `invalid runtime handler: ${item}`);
}
const runtime = unique(handlerItems.map((item) => item.split("::").at(-1)), "runtime handlers");

const manifestBody = oneBody(
  read("build.rs"),
  /AppManifest::new\(\)\.commands\(&\[([\s\S]*?)\]\)/g,
  "AppManifest commands",
);
const manifestItems = manifestBody.split(",").map((item) => item.trim()).filter(Boolean);
assert.ok(manifestItems.length > 0, "AppManifest command inventory is empty");
for (const item of manifestItems) {
  assert.match(item, /^"[a-z][a-z_0-9]*"$/, `invalid AppManifest command: ${item}`);
}
const manifest = unique(manifestItems.map((item) => item.slice(1, -1)), "AppManifest commands");
equalSets(manifest, runtime, "AppManifest versus runtime handlers");

const generatedFiles = fs.readdirSync(path.join(root, "permissions", "autogenerated"))
  .filter((file) => file.endsWith(".toml"));
const generated = unique(generatedFiles.map((file) => file.slice(0, -5)), "generated permission files");
equalSets(generated, manifest, "generated application permissions versus AppManifest");
for (const command of manifest) {
  const source = read(`permissions/autogenerated/${command}.toml`);
  const blocks = source.split(/(?=^\[\[permission\]\]$)/m)
    .filter((block) => block.startsWith("[[permission]]"));
  assert.equal(blocks.length, 2, `${command}: expected one allow and one deny definition`);
  for (const [index, action] of ["allow", "deny"].entries()) {
    const id = `${action}-${command.replaceAll("_", "-")}`;
    const verb = action === "allow" ? "Enables" : "Denies";
    assert.deepEqual(blocks[index].trim().split(/\r?\n/), [
      "[[permission]]",
      `identifier = "${id}"`,
      `description = "${verb} the ${command} command without any pre-configured scope."`,
      `commands.${action} = ["${command}"]`,
    ], `${command}: invalid ${action} generated permission`);
  }
}

const capability = JSON.parse(read("capabilities/default.json"));
assert.equal(capability.identifier, "default");
assert.deepEqual(capability.windows, ["main"]);
assert.ok(Array.isArray(capability.permissions), "default capability permissions must be an array");
const permissions = unique(capability.permissions, "default capability permissions");
assert.equal([...permissions].some((permission) => permission.includes("*")), false, "wildcard permission is forbidden");
assert.equal([...permissions].some((permission) => /(^|:|-)fs($|:|-)/i.test(permission)), false, "filesystem plugin permission is forbidden");
const core = new Set([...permissions].filter((permission) => permission.startsWith("core:")));
equalSets(core, new Set(["core:event:allow-listen", "core:event:allow-unlisten"]), "core event permissions");
const dialog = new Set([...permissions].filter((permission) => permission.startsWith("dialog:")));
equalSets(dialog, new Set(["dialog:allow-open"]), "dialog plugin permissions");
const appAllows = new Set([...permissions].filter((permission) => !permission.includes(":")));
equalSets(appAllows, new Set([...manifest].map(allowId)), "default application allows versus AppManifest");

// index.html loads status.js as the production frontend script.
assert.match(read("frontend/index.html"), /<script src="status\.js"><\/script>/);
const frontend = read("frontend/status.js");
const invokes = [...frontend.matchAll(/\binvoke\s*\(\s*([^,)]*)/g)];
assert.ok(invokes.length > 0, "production frontend invoke inventory is empty");
const frontendCommands = [];
const literal = /^"([a-z][a-z_0-9]*)"$/;
const conditional = /^(?:[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*(?:\s*(?:===|!==)\s*"[a-z][a-z_0-9]*")?)\s*\?\s*"([a-z][a-z_0-9]*)"\s*:\s*"([a-z][a-z_0-9]*)"$/;
for (const [, argument] of invokes) {
  const expression = argument.trim();
  const single = expression.match(literal);
  const pair = expression.match(conditional);
  assert.ok(single || pair, `unsupported frontend invoke argument: ${expression}`);
  frontendCommands.push(...(single ? [single[1]] : pair.slice(1)));
}
const frontendSet = new Set(frontendCommands);
for (const [label, inventory] of [
  ["runtime", runtime],
  ["AppManifest", manifest],
  ["default capability", new Set([...appAllows].map((id) => id.slice(6).replaceAll("-", "_")))],
]) {
  const missing = [...frontendSet].filter((command) => !inventory.has(command)).sort();
  assert.deepEqual(missing, [], `production frontend invokes missing from ${label}`);
}

for (const command of ["host_prepare_repo_edit_files", "host_prepare_repo_create_file", "host_prepare_repo_delete_file"]) {
  assert.ok(frontendSet.has(command), `${command} must remain a production frontend invoke`);
}
for (const command of ["host_confirm_tool_invocation", "host_cancel_tool_invocation", "host_prepare_repo_rename_file", "repository_membership", "remove_repository_member", "activate_repository_member", "close_repository"]) {
  assert.ok(runtime.has(command), `${command} must remain a runtime handler`);
  assert.ok(appAllows.has(allowId(command)), `${command} must remain allowed for main`);
}
console.log(`Tauri permission inventory passed: ${runtime.size} runtime, ${manifest.size} manifest, ${generated.size} generated, ${appAllows.size} default allows; ${frontendSet.size} frontend commands`);
